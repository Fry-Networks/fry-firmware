#!/usr/bin/env python3
"""Generate src/esp8266/tls_anchors.h - the ESP8266 BearSSL trust-anchor set - from the vendored
Mozilla CA bundle.

    python3 tools/gen_tls_anchors.py [--check]

--check regenerates into memory and fails if the checked-in header differs (run it in review and in
CI-style checks; it writes nothing).

Why three roots and not the whole Mozilla store: the ESP8266 keeps every trust anchor in the heap
for the life of the boot (BearSSL::X509List copies the DER certificate, the DER subject name and
the public key of each), and the measured cost of the six-anchor bench set was 7,704 B of free heap
and 9,136 B of the largest contiguous block - on a chip whose OTA download gate wants a 36,864 B
block. The three below are the minimum that validates every chain this firmware actually sees
(chains captured 2026-10-23, see the repo's recon note):

  hardwareapi.frynetworks.com, fry.farm, dashboard.frynetworks.com
      leaf <- Let's Encrypt YE2/YE1 <- ISRG Root YE <- ISRG Root X2
      ISRG Root YE's certificate is issued by ISRG Root X2.
  github.com
      leaf <- Sectigo Public Server Authentication CA DV E36 <- Sectigo Root E46 <- USERTrust ECC
      The DV E36 certificate is issued by Sectigo Root E46.
  release-assets.githubusercontent.com, objects.githubusercontent.com
      leaf <- Let's Encrypt YR1 <- ISRG Root YR (cross-signed by ISRG Root X1)
      The ISRG Root YR certificate is issued by ISRG Root X1.

BearSSL's trust-anchor check (x509_minimal.c, check_single_trust_anchor_CA) matches an anchor
against a certificate's ISSUER name and verifies that certificate's signature with the anchor's
key, so the anchor does not have to be one of the certificates in the wire chain - which is why
X1 validates the YR-cross-signed hop and X2 validates the YE hop.

Rotation risk (accepted by the lead): these CAs are mid-rotation; a rotation that stops a host
from sending its cross-signing certificate would strand that host, and OTA is the mechanism that
would need fixing. Re-generate with more roots only alongside a measured heap budget.
"""
import base64
import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MOZ = ROOT / "data/cert/mozilla_cacert_2026-08-13.pem"
OUT = ROOT / "src/esp8266/tls_anchors.h"

# Order is the order in the generated blob and in the comment index. Keep it stable: the bench
# tooling and the docs refer to these indexes.
WANT = [
    "ISRG Root X2",
    "Sectigo Public Server Authentication Root E46",
    "ISRG Root X1",
]


def split_pem(text):
    """label -> PEM block, using curl.se's 'Label\\n=====' section headers."""
    out = {}
    cur = None
    pending = None
    for line in text.splitlines():
        if line.startswith("-----BEGIN CERTIFICATE-----"):
            cur = [line]
        elif cur is not None:
            cur.append(line)
            if line.startswith("-----END CERTIFICATE-----"):
                if pending is None:
                    sys.exit("REFUSED: certificate block without a label header")
                out.setdefault(pending, "\n".join(cur))
                cur = None
        elif line and set(line) == {"="}:
            continue
        elif line.strip() and not line.startswith("#"):
            pending = line.strip()
    return out


def der_len(pem):
    return len(base64.b64decode("".join(pem.splitlines()[1:-1])))


def render():
    raw = MOZ.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    certs = split_pem(raw.decode("utf-8"))
    missing = [n for n in WANT if not certs.get(n)]
    if missing:
        sys.exit("REFUSED: anchors not found in %s: %r" % (MOZ.name, missing))

    lines = [
        "#pragma once",
        "// GENERATED by tools/gen_tls_anchors.py - do not hand-edit. Regenerate with:",
        "//   python3 tools/gen_tls_anchors.py",
        "//",
        "// The ESP8266 BearSSL trust-anchor set: %d roots, the minimum that validates every chain"
        % len(WANT),
        "// this firmware contacts (see the script's header for the chains and the reasoning).",
        "// Public root certificates only - no key material, nothing secret.",
        "//",
        "// Source: data/cert/%s" % MOZ.name,
        "//   sha256 %s" % digest,
        "//",
        "// Order is the order reported by the bench 'anchor[i]' lines:",
    ]
    for i, name in enumerate(WANT):
        lines.append("//   %d: %s (%d DER bytes)" % (i, name, der_len(certs[name])))
    lines += [
        "#include <Arduino.h>",
        "",
        "// X509List::append() parses every CERTIFICATE block in one call, so one PROGMEM blob.",
        "static const char kTlsAnchorsPem[] PROGMEM = R\"PEM(",
    ]
    for name in WANT:
        lines.append(certs[name])
    lines += [")PEM\";", ""]
    return "\n".join(lines), digest


def main():
    text, digest = render()
    if "--check" in sys.argv:
        if not OUT.exists():
            sys.exit("REFUSED: %s is missing" % OUT)
        if OUT.read_text() != text:
            sys.exit("REFUSED: %s is out of date; rerun tools/gen_tls_anchors.py" % OUT)
        print("%s is up to date (source sha256 %s)" % (OUT.name, digest))
        return 0
    OUT.write_text(text)
    print("wrote %s (%d bytes, %d anchors, source sha256 %s)"
          % (OUT, len(text), len(WANT), digest))
    return 0


if __name__ == "__main__":
    sys.exit(main())
