#!/usr/bin/env python3
"""Generates src/boards/tls_roots.h: the three trust roots of the Pico and BK7231N builds as PEM text.

Same roots as the ESP8266 anchors (tools/gen_tls_anchors.py), picked by the SHA-256 of their DER pinned there, so a renamed or
substituted certificate is refused. One PEM per trust set of lib/fry_core/tls_trust.h (Hwapi, GithubCom, GithubAssets).

  tools/gen_boards_tls_roots.py          write src/boards/tls_roots.h
  tools/gen_boards_tls_roots.py --check  exit 1 if the file on disk differs
"""
import base64
import importlib.util
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "boards" / "tls_roots.h"

spec = importlib.util.spec_from_file_location("gen_tls_anchors", ROOT / "tools" / "gen_tls_anchors.py")
gta = importlib.util.module_from_spec(spec)
spec.loader.exec_module(gta)


def pem(der):
    b64 = base64.b64encode(der).decode()
    return "-----BEGIN CERTIFICATE-----\n" + "\n".join(textwrap.wrap(b64, 64)) + "\n-----END CERTIFICATE-----\n"


def render():
    out = ["#pragma once",
           "// GENERATED by tools/gen_boards_tls_roots.py from data/cert/*.pem; never hand-edited (--check).",
           "// One root per trust set (lib/fry_core/tls_trust.h): the roots the live chains end at, picked by the pinned SHA-256 of",
           "// their DER (tools/gen_tls_anchors.py). The Pico (BearSSL X509List) and BK7231N (mbedtls setCACert) builds load these.",
           ""]
    for set_name, label, roots in gta.SETS:
        der = gta.der_for(roots[0])
        out.append("// %s" % label)
        out.append('static const char kRootPem%s[] =' % set_name)
        for line in pem(der).splitlines():
            out.append('    "%s\\n"' % line)
        out[-1] += ";"
        out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else 1)
    OUT.write_text(text)
    print("wrote", OUT)
